"""Regenerates icons_data.h for PromptPad from catppuccin/zed-icons.

Needs:
    pip install resvg-py pillow
    git clone --depth 1 https://github.com/catppuccin/zed-icons

Usage:
    python tools/gen_icons.py <path-to-zed-icons> <path-to-icons_data.h>
"""

import base64
import io
import json
import os
import re
import sys

from PIL import Image
import resvg_py

CELL = 40      # rendered size of one icon, drawn at 16-32 px on screen
COLS = 20
FLAVOUR = "Catppuccin Mocha"
MONO = "#C6D0DA"   # every icon is recoloured to this single line colour


def monochrome(svg: str) -> str:
    """Flatten the Catppuccin palette into one line colour."""
    svg = re.sub(r'(stroke|fill)="(?!none)([^"]*)"',
                 lambda m: '%s="%s"' % (m.group(1), MONO), svg)
    svg = re.sub(r'(stroke|fill):\s*(?!none)[^;"\s]+',
                 lambda m: '%s:%s' % (m.group(1), MONO), svg)
    return svg


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1

    repo = sys.argv[1]
    out_path = sys.argv[2]

    theme_json = os.path.join(repo, "icon_themes", "catppuccin-icons.json")
    icon_dir = os.path.join(repo, "icons", "mocha")

    with open(theme_json, encoding="utf-8") as f:
        doc = json.load(f)
    theme = [t for t in doc["themes"] if t["name"] == FLAVOUR][0]

    suffixes = theme.get("file_suffixes", {})
    stems = theme.get("file_stems", {})

    needed = set(suffixes.values()) | set(stems.values())
    needed |= {"_file", "_folder", "image", "url"}

    needed = sorted(n for n in needed if os.path.exists(os.path.join(icon_dir, n + ".svg")))
    print("icons:", len(needed))

    cells = []
    for name in needed:
        with open(os.path.join(icon_dir, name + ".svg"), encoding="utf-8") as f:
            svg = monochrome(f.read())
        png = resvg_py.svg_to_bytes(svg_string=svg, width=CELL, height=CELL)
        img = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
        if img.size != (CELL, CELL):
            canvas = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
            canvas.paste(img, ((CELL - img.width) // 2, (CELL - img.height) // 2), img)
            img = canvas
        cells.append((name, img))

    rows = (len(cells) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    index = {}
    for i, (name, img) in enumerate(cells):
        sheet.paste(img, ((i % COLS) * CELL, (i // COLS) * CELL), img)
        index[name] = i

    buf = io.BytesIO()
    sheet.save(buf, "PNG", optimize=True)
    png = buf.getvalue()
    print("sheet:", sheet.size, "png bytes:", len(png))
    b64 = base64.b64encode(png).decode("ascii")

    def icon_id(name):
        return index.get(name, index["_file"])

    suffix_rows, seen = [], set()
    for key, icon in suffixes.items():
        k = key.lower()
        if not k or k in seen:
            continue
        seen.add(k)
        suffix_rows.append((k, icon_id(icon)))
    suffix_rows.sort(key=lambda r: (-len(r[0]), r[0]))

    stem_rows, seen = [], set()
    for key, icon in stems.items():
        k = key.lower()
        if not k or k in seen:
            continue
        seen.add(k)
        stem_rows.append((k, icon_id(icon)))
    stem_rows.sort()

    L = []
    L.append("// Generated by tools/gen_icons.py from")
    L.append("// https://github.com/catppuccin/zed-icons (" + FLAVOUR + ", MIT licence).")
    L.append("// %dx%d px per icon, packed into one sheet." % (CELL, CELL))
    L.append("#pragma once")
    L.append("")
    L.append("static const int kIconCell  = %d;" % CELL)
    L.append("static const int kIconCols  = %d;" % COLS)
    L.append("static const int kSheetW    = %d;" % sheet.width)
    L.append("static const int kSheetH    = %d;" % sheet.height)
    L.append("static const int kIconFile   = %d;" % index["_file"])
    L.append("static const int kIconFolder = %d;" % index["_folder"])
    L.append("static const int kIconImage  = %d;" % index["image"])
    L.append("static const int kIconUrl    = %d;" % index["url"])
    L.append("")
    L.append("struct IconName { const wchar_t* name; int id; };")
    L.append("static const IconName kIconNames[] = {")
    for name, i in index.items():
        L.append('    { L"%s", %d },' % (name, i))
    L.append("};")
    L.append("")
    L.append("struct IconRule { const wchar_t* key; short icon; };")
    L.append("")
    L.append("// longest suffix first: the first match wins")
    L.append("static const IconRule kIconSuffixes[] = {")
    for key, icon in suffix_rows:
        L.append('    { L"%s", %d },' % (key, icon))
    L.append("};")
    L.append("")
    L.append("// exact file name (without extension) -> icon")
    L.append("static const IconRule kIconStems[] = {")
    for key, icon in stem_rows:
        L.append('    { L"%s", %d },' % (key, icon))
    L.append("};")
    L.append("")
    L.append("static const char kIconsPngB64[] =")
    for i in range(0, len(b64), 100):
        L.append('    "%s"' % b64[i:i + 100])
    L.append(";")
    L.append("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))

    print("written:", out_path, os.path.getsize(out_path), "bytes")
    print("suffix rules:", len(suffix_rows), "stem rules:", len(stem_rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
